/**
 * Правила округлення.
 *
 * Гроші зберігаються цілими копійками (поля `*Kop`), тому для них округлення
 * потрібне лише при множенні кількості на ціну (`Math.round`). Кількості ж
 * можуть бути дробовими (літри, метри), і тут діє окреме правило.
 */

/**
 * Округлює кількість до трьох знаків після коми.
 * Прибирає «шум» плаваючої коми: `0.1 + 0.2` дає `0.3`, а не `0.30000000000000004`.
 * Без цього залишок партії міг би стати `0.00000000000000004` замість нуля.
 */
export function roundQty(qty: number): number {
  return Math.round(qty * 1000) / 1000
}
